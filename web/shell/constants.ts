// Measurements of the shell in px.

/** Height of the bar along the bottom edge of the screen. */
export const STATUS_BAR_H = 30;
/** Gap between that bar and the window layer. */
export const STATUS_BAR_MARGIN = 12;

/** Bottom edge of the window layer: bar, its margin and 10 px of slack. */
export const STAGE_BOTTOM = STATUS_BAR_H + STATUS_BAR_MARGIN + 10;

/** Height of one window title bar. */
export const TITLEBAR_H = 38;

/** Smallest size a window can be dragged to. */
export const WINDOW_MIN_W = 420;
export const WINDOW_MIN_H = 260;

/** Offset per already-open window when placing a new one. */
export const WINDOW_CASCADE = 28;
